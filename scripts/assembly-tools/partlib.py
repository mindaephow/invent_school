def get(name):
    return frame(name) or OTHER[name]

def build_all():
    conn, dims = {}, {}
    for n in FRAMES + list(OTHER):
        c = get(n)
        conn[n] = {"pegs": c.get("pegs", []), "holes": c.get("holes", [])}
        dims[n] = c["size"]
    return conn, dims

