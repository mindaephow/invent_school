def _addhide(pt, steps_, label):                                  # 부품을 그 단계들에서 안 보이게(창고에 보관)
    ex = pt.extra; ex["hideAt"] = sorted(set(ex.get("hideAt", [])) | set(steps_)); st_ = ex.setdefault("store", {})
    for k_ in steps_: st_[str(k_)] = label
