def _abs_place(st, n, R, p, **extra):
    """절대 좌표로 놓는다 — place 의 '앞 부품 옆 상대 위치' 잠금(_anchored)을 쓰지 않는다(부품 치우침 때문에 좌표를 미세 조정하는 부품용)."""
    st._resolve_lazy(n, R, p, extra); st._lock_extra(n, extra)
    return st._add(Part(n, R, p, st, extra))
