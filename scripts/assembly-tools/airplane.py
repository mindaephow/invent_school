A = Asm("cubo-1-airplane", "조종형비행기", "교재 ?~?쪽 · 조종형비행기 (1~?단계)", camera={"target": [60, 20, 0], "radius": 380, "theta": 0.9, "phi": 1.0},
        listNote="만드는 중 — 단계가 끝나기 전까지 LIST 개수는 안 맞는 것이 정상", guideMode="mates")   # 연결점은 부품에 붙어 있고 결합할 자리일 때만 보인다(사용자 지시 2026-10-04)
RELOCK = "--relock" in sys.argv   # 잠금 기록을 새로 만들 때(수정 지시는 이번 빌드에서 무시한다)
if not RELOCK: A.load_fixes("airplane_fixes.json")   # 관리자 수정 지시(앞 단계 수정 → 뒤 단계가 따라온다). 파일이 없으면 아무 일도 안 한다
A.load_links("airplane_links.json", relock=RELOCK)   # 좌표로 쓴 결합·절대 좌표로 놓은 판을 이름으로 잠가 두는 기록
UP = (0, 1, 0)

# ── 1 ── 교재 73쪽 1: 315프레임에 리벳 2개(이미 꽂힘) → 90도 프레임 → DC모터(뒷면이 위, 앞돌기 2개가 프레임 가운데 줄 열11·열15에)
# 읽은 것: 315프레임 3줄×15칸(먼 줄=줄1, 열1=왼쪽 끝). 리벳은 열3·줄1 과 열1·줄2. 90도 프레임은 모서리가 열1·줄1 위, 가로 팔(+x)·세로 팔(+z).
#         초록 원 = 90도 프레임의 가로 팔 끝 구멍(→열3·줄1 리벳)과 세로 팔 가운데 구멍(→열1·줄2 리벳), 프레임 줄2 의 열11·열15(DC모터 앞돌기 간격 40).
s1 = A.step("[교재 1] 315프레임 열3·줄1 과 열1·줄2 에 리벳 2개를 꽂고, 그 위에 90도 프레임(모서리가 열1·줄1)을 끼워요. DC모터는 뒤집어서(뒷면이 위) 앞쪽 돌기 2개를 프레임 가운데 줄의 열11·열15 구멍에 꽂아요.")
P = s1.place("315프레임", np.eye(3), (75, 2.5, 0))                       # 긴 쪽 x(열1이 왼쪽), 구멍축 y, 줄1 = z −10(먼 줄)
rvA = s1.attach("리벳", np.eye(3), {"돌기면 -y 1": (P, "홀면 +y 열3·줄1")}, rivet=True)
rvB = s1.attach("리벳", np.eye(3), {"돌기면 -y 1": (P, "홀면 +y 열1·줄2")}, rivet=True)
ang90 = s1.recv("90도 프레임", np.eye(3), {"홀면 -y 열3·줄1": (rvA, "돌기면 +y 1"), "홀면 -y 열1·줄2": (rvB, "돌기면 +y 1")}, hover=50)   # 리벳(22mm 위에 떠 있음)보다 높이 떠야 리벳이 90도 프레임 아래 중간에 보인다(사용자 스크린샷)
R_DC = orient("DC모터", {"돌기면 +y": "아래", "축 +z": "-X"})              # 앞돌기 면이 아래, 케이블 쪽(모델 +z)이 왼쪽(−x)
motor = s1.attach("DC모터", R_DC, {"돌기면 +y 열1·줄2": (P, "홀면 +y 열11·줄2"), "돌기면 +y 열1·줄1": (P, "홀면 +y 열15·줄2")}, hover=30)
ang90.extra["faceMarks"] = [[m_[0], ang90.p[1] + 2.5, m_[2]] for m_ in ang90.extra["marks"]]   # 초록 점은 리벳 돌기 끝(판 안쪽)이 아니라 90도 프레임 윗면 구멍 높이에 — 그래야 점이 판 두께 가운데에 온다(사용자 지시)
ang90.extra["joinOrder"] = 2; motor.extra["joinOrder"] = 2   # 사용자 지시: 리벳을 꽂는 과정도 보여 준다 — 리벳 2개를 먼저 꽂고(1) 그다음 90도 프레임·모터가 내려온다(2)

# ── 2 ── 교재 73쪽 2: 2단블록 4개를 끝돌기로 세워서 줄1 구멍에 (왼쪽 둘 = 90도 프레임 열1·열2, 가운데 = 열4, 오른쪽 = 열10)
# 읽은 것: 블록 4개 모두 윗면에 돌기 2개(2단블록의 ±z 면), 아래로 향한 끝돌기 1개가 초록 원 안으로 들어간다. 초록 원 위치는 줄1: 90도 프레임 2곳, 프레임 열4, 열10.
s2 = A.step("[교재 2] 1번 완성품을 세우고, 반대편(뒷면)에서 2단블록 4개를 줄1 구멍에 꽂아요: 왼쪽 둘은 315프레임 열1·열2(90도 프레임 뒤), 나머지 둘은 열4·열10.")
s2.move_built(rot_x(90), floor=True)   # 교재 2: 1단계까지의 완성품이 자동으로 한 그룹 — 한 덩어리로 세운다(구멍 면이 보는 쪽 +Z, 줄1이 위쪽 줄)
R_STAND = orient("2단블록", {"돌기면 -x": "+Z", "돌기면 +z": "위"})   # 블록은 세워진 프레임의 반대편(뒤, −y 면)에서 넘어온다: 끝돌기(-x)가 +Z(보는 쪽)를 향해 구멍에 들어가고 2개짜리 면이 위
b1 = s2.attach("2단블록", R_STAND, {"돌기면 -x 1": (P, "홀면 -y 열1·줄1")}, hover=40)
b2 = s2.attach("2단블록", R_STAND, {"돌기면 -x 1": (P, "홀면 -y 열2·줄1")}, hover=40)
b3 = s2.attach("2단블록", R_STAND, {"돌기면 -x 1": (P, "홀면 -y 열4·줄1")}, hover=40)
b4 = s2.attach("2단블록", R_STAND, {"돌기면 -x 1": (P, "홀면 -y 열10·줄1")}, hover=40)

# ── 3 ── 교재 74쪽 3: 축을 90도 프레임 세로 팔 맨 아래 구멍(열1·줄3)에 앞에서 끼워 315프레임을 지나 뒤로, 뒤에 작은기어 2개, 앞 끝에 부시
# 읽은 것: 초록 원이 한 직선 위에 있다 — 부시(앞) → 축 → 90도 프레임 열1·줄3 구멍 → 뒤쪽 작은기어 2개. 블록 4개는 프레임 뒤로 솟아 보인다(2단계와 같음).
#   축(65)은 앞 끝이 부시와 평평(z 6.9)이고 뒤로 315프레임 뒷면(z −10.1)을 지나 −58.1 까지. 기어(두께 8)는 프레임 뒷면에 붙여 −14.1, −22.1. 부시(5.5)는 90도 프레임 앞면(z 1.4) 위 4.15.
s3 = A.step("[교재 3] 축을 90도 프레임 맨 아래 구멍(열1·줄3)에 앞에서 끼워 315프레임을 지나 뒤로 보내고, 프레임 뒤쪽 축에 작은기어 2개, 앞쪽 끝에 부시를 끼워요.")
hx, hy = 5.0, 10.0                                                         # 90도 프레임 열1·줄3 구멍의 축(세워진 뒤, z 방향으로 뚫림)
Z_FRONT, Z_BACK = 6.9, 6.9 - 65
R_AX = orient("축", {"돌기면 +y": "-Z"})                                    # 축(모델 y 방향으로 65) → 세계 z, 돌기 끝이 -Z(들어가는 방향)
axle = s3.place("축", R_AX, (hx, hy, (Z_FRONT + Z_BACK) / 2), dir=[0, 0, 1], hover=75, pegDepth=40, marks=[[hx, hy, 1.4]])
R_GEAR = ori("+x", "+z")                                                   # 기어·부시: 구멍축(모델 y) → 세계 z
gA = s3.place("작은기어", R_GEAR, (hx, hy, -14.1), recv=True, dir=[0, 0, -1], hover=30, marks=[[hx, hy, Z_BACK]])
gB = s3.place("작은기어", R_GEAR, (hx, hy, -22.1), recv=True, dir=[0, 0, -1], hover=65, marks=[[hx, hy, Z_BACK]])
bush = s3.place("부시", rot_x(180) @ R_GEAR, (hx, hy, 4.15), recv=True, dir=[0, 0, 1], hover=100, marks=[[hx, hy, Z_FRONT]])
gA.extra["thick"] = gB.extra["thick"] = 8; bush.extra["thick"] = 5.5   # 초록 십자 표시를 부품 두께의 가운데(십자 구멍 한가운데)에
gA.extra["faceMarks"] = [[hx, hy, -14.1 - 4]]; gB.extra["faceMarks"] = [[hx, hy, -22.1 - 4]]; bush.extra["faceMarks"] = [[hx, hy, 4.15 + 2.75]]
axle.extra["holeMarks"] = [[hx, hy, 1.4]]   # 90도 프레임 열1·줄3 구멍에 초록 연결점(교재 3)
axle.extra["joinOrder"] = 1; gA.extra["joinOrder"] = 2; gB.extra["joinOrder"] = 2; bush.extra["joinOrder"] = 3   # 축을 먼저 끼우고, 기어를 뒤에서, 부시를 앞에서

# ── 4 ── 교재 74쪽 4: 1단계 프레임을 거울에 비춘 판 한 벌(315프레임 + 리벳 2 + 90도 프레임)이 한 덩어리로 블록 4개의 남은 끝돌기에 끼워진다
# 읽은 것: 블록 4개의 남은 끝돌기는 사용자 쪽(−z)을 향한다. 판 한 벌은 블록 중간 면(z −20.1)에 대해 1번 판과 거울 자리(판 중심 z −32.6, L 은 바깥쪽 −z). 열1·열2 블록 돌기는 L 구멍으로,
#         열4·열10 블록 돌기는 판 구멍(교재 M1·M2)으로, 축의 뒤쪽 끝은 L 의 맨 아래 구멍(열1·줄3)으로 들어간다. 판 한 벌은 이미 조립된 모양으로 한꺼번에 내려온다(교재 4).
s4 = A.step("[교재 4] 315프레임 2번의 줄1·열3, 줄2·열1 구멍에 리벳 3·4번을 끼우고, 90도 프레임 2번을 +z 로 움직여 리벳에 결합해요. 그 묶음을 통째로 +z 로 움직여 블록 4개의 돌기와 결합해요(축만 315프레임 줄3·열1 구멍을 통과).")
R_PL = rot_x(90)                                                           # 1번 판과 같은 자세(구멍축 z, 줄1이 위)
def tip(blk): g = blk.peg("p1"); return [round(float(v), 3) for v in g["pos"] + g["dir"] * g["len"] / 2]   # 블록 남은 끝돌기 끝
AX_TIP = [hx, hy, Z_BACK]                                                   # 축 뒤쪽 끝(3단계에서 끼운 것이 315프레임 줄3·열1 구멍과 90도 프레임 구멍을 통과)
plate2 = s4.place("315프레임", R_PL, (75, 20, 2 * -20.1 - -7.6), recv=True, dir=[0, 0, -1], hover=40, marks=[tip(b1), tip(b2), tip(b3), tip(b4), AX_TIP])
plate2.extra["faceMarks"] = [[m_[0], m_[1], -35.1] for m_ in plate2.extra["marks"]]   # 초록 점은 판 두께의 가운데에(블록 돌기 4곳 + 축 1곳)
R_RV2 = orient("리벳", {"돌기면 -y": "+Z"})                                 # 아래돌기가 +Z(판 구멍 쪽)
rvC = s4.attach("리벳", R_RV2, {"돌기면 -y 1": (plate2, "홀면 -y 열3·줄1")}, hover=65)    # 사용자 순서(2026-10-04): 리벳 3번 → 315프레임 2번 −y쪽 줄1·열3
rvD = s4.attach("리벳", R_RV2, {"돌기면 -y 1": (plate2, "홀면 -y 열1·줄2")}, hover=65)    #                          리벳 4번 → 줄2·열1
ang90b = s4.recv("90도 프레임", rot_x(90), {"홀면 +y 열3·줄1": (rvC, "돌기면 +y 1"), "홀면 +y 열1·줄2": (rvD, "돌기면 +y 1")}, hover=90)   # 90도 프레임 2번이 +z 로 움직여 리벳 3·4번에 결합
ang90b.extra["marks"] = list(ang90b.extra.get("marks", [])) + [AX_TIP]; ang90b.extra["dir"] = [0, 0, -1]   # 구멍 3곳: 리벳 2 + 축 1 (블록과는 결합 안 함)
ang90b.extra["faceMarks"] = [[m_[0], m_[1], ang90b.p[2] - 2.5] for m_ in ang90b.extra["marks"]]   # 초록 점은 90도 프레임 두께의 가운데에
rvC.extra["pegDepth"] = rvD.extra["pegDepth"] = 3   # 리벳 돌기 길이 3 — 돌기 끝 점이 리벳 끝에 딱 붙게
rvC.extra["guideShift"] = rvD.extra["guideShift"] = [0, 0, -40]   # 리벳이 끼워질 구멍은 40mm 떠 있는 판(plate2)에 있으니 화살표·점도 그 자리로
plate2.extra["joinOrder"] = 1; rvC.extra["joinOrder"] = rvD.extra["joinOrder"] = 2; ang90b.extra["joinOrder"] = 3   # 판 → 리벳 → 90도 프레임(위에서부터 그룹으로 +z 로 통째 이동해 블록들과 결합)

# ── 5 ── 교재 74쪽 5: 새 판(바깥 면)에 DC모터 2번째를 끼우고, 축 끝(새 판 바깥으로 나온 곳)에 부시를 끼운다
