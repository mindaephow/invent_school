bush2 = s5.place("부시", R_GEAR, (hx, hy, -41.6 - 2.75), recv=True, dir=[0, 0, -1], hover=60, marks=[[hx, hy, Z_BACK]])
bush2.extra["thick"] = 5.5; bush2.extra["faceMarks"] = [[hx, hy, -41.6 - 5.5]]

# ── 6 ── 교재 74쪽 6: 25프레임 2개에 리벳 2개씩(대각선으로 꽂음) → 2열브라켓 2개를 위에서 내려 결합(왼쪽 브라켓·오른쪽 브라켓). 본체와는 따로 만드는 조립품 2개(7번에서 본체에 올라간다).
# 읽은 것: 리벳 위치는 25프레임 끝 쪽 두 칸(열1과 열2)이 대각선이고, 왼쪽·오른쪽 브라켓은 서로 거울이라 대각선이 반대다. 브라켓은 넓은 면(구멍 2×2)이 리벳 위에 앉고 세운 팔은 끝(열1쪽)에 선다. 위치는 본체 옆 빈자리(아직 모름 → 7번에서 옮김).
