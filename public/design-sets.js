// 조립 "세트" 정의. design.html에 있던 SETS 계산 로직을 그대로 옮긴 것 — 새 세트를 추가할 땐 이 파일만 고치면 됨.
window.IVS_SETS = (function(){
  // 세트: 여러 부품을 조립한 채로 한 번에 놓는다. 위치(x,y,z 단위 mm)와 각도(X·Y·Z °)는 저장해 둔 그대로.
  const SETS = {
    lset: {
      label: 'ㄴ셋',
      parts: [
        { type: 'panel',    pos: [-110, 5, -110],   rot: [0, 0, 0] },   // 바닥판
        { type: 'lbracket', pos: [-220, 28, -220],  rot: [0, 0, 90] },  // A1
        { type: 'lbracket', pos: [0, 28, -220],     rot: [0, 0, 90] },  // A12
        { type: 'panel',    pos: [-110, 138, -233], rot: [90, 0, 0] }   // 세운 벽판
      ]
    },
    // ㄱ셋 = ㄴ셋을 위아래로 뒤집은 모양: 같은 벽판, 판·연결대는 벽 높이(가운데 138)를 기준으로 뒤집은 높이(276 - y)
    gset: {
      label: 'ㄱ셋',
      parts: [
        { type: 'panel',    pos: [-110, 271, -110],  rot: [0, 0, 0] },   // 위쪽 판
        { type: 'lbracket', pos: [-220, 248, -220],  rot: [0, 0, 90] },  // A1
        { type: 'lbracket', pos: [0, 248, -220],     rot: [0, 0, 90] },  // A12
        { type: 'panel',    pos: [-110, 138, -233],  rot: [90, 0, 0] }   // 세운 벽판
      ]
    },
    // ㅁ셋 = ㄴ셋 + ㄱ셋 + 앞벽: 바닥판·위쪽 판, 뒷벽·앞벽(판 가운데 z=-110 기준 대칭)을 ㄱ자연결대 8개로 이은 상자(옆에서 보면 네모)
    mset: {
      label: 'ㅁ셋 1',
      parts: [
        { type: 'panel', pos: [-110, 5, -110],   rot: [0, 0, 0] },   // 바닥판
        { type: 'panel', pos: [-110, 271, -110], rot: [0, 0, 0] },   // 위쪽 판
        { type: 'panel', pos: [-110, 138, -233], rot: [90, 0, 0] },  // 뒷벽
        { type: 'panel', pos: [-110, 138, 13],   rot: [90, 0, 0] },  // 앞벽
        ...[-220, 0].flatMap(z => [28, 248].flatMap(y => [-220, 0].map(x => ({ type: 'lbracket', pos: [x, y, z], rot: [0, 0, 90] }))))
      ]
    }
  };
  // ㄷ셋 = ㅁ셋 1에서 앞벽과 앞쪽 연결대 4개를 뺀 것: 바닥판·위쪽 판이 뒷벽 하나에 이어진 모양(옆에서 보면 ㄷ)
  SETS.dset = {
    label: 'ㄷ셋 1',
    parts: SETS.mset.parts.filter(sp => !(sp.type === 'lbracket' && sp.pos[2] === 0) && !(sp.type === 'panel' && sp.pos[2] === 13))
  };
  // ㄷ셋 2 = ㄷ셋 1 전체를 X축으로 +90° 돌린 것 (조립체 가운데 y=138, z=-110 둘레): 뒷벽이 지붕이 되고 바닥판·위쪽 판이 앞뒤 벽으로 선다.
  // 각도는 회전을 합성해 구한 값(X→Y→Z 순서): 눕힌 판 [0,0,0]→[90,0,0], 세운 벽 [90,0,0]→[180,0,0], 연결대 [0,0,90]→[0,-90,90]
  SETS.dset2 = {
    label: 'ㄷ셋 2',
    parts: [
      { type: 'panel',    pos: [-110, 138, -233], rot: [90, 0, 0] },   // 앞뒤 벽 (뒤) — 연결대 몸통에 밀착
      { type: 'panel',    pos: [-110, 138, 13],   rot: [90, 0, 0] },   // 앞뒤 벽 (앞) — 연결대 몸통에 밀착
      { type: 'panel',    pos: [-110, 271, -110],  rot: [180, 0, 0] },  // 지붕 (연결대 위 핀 끝이 판 윗면과 딱 맞는 높이)
      { type: 'lbracket', pos: [-220, 248, -220], rot: [0, -90, 90] },
      { type: 'lbracket', pos: [0, 248, -220],    rot: [0, -90, 90] },
      { type: 'lbracket', pos: [-220, 248, 0],    rot: [0, -90, 90] },
      { type: 'lbracket', pos: [0, 248, 0],       rot: [0, -90, 90] }
    ]
  };
  // ㄷ셋 3 = ㄷ셋 2를 X축으로 180° 뒤집은 것 (같은 가운데 y=138, z=-110 둘레): 지붕이 바닥판이 되고 앞뒤 벽은 서 있는 채 자리만 바뀐다(∪ 모양).
  // 각도는 회전을 합성해 구한 값: 벽 [90,0,0]→[-90,0,0], 지붕 [180,0,0]→[0,0,0], 연결대 [0,-90,90]→[0,90,90]
  SETS.dset3 = {
    label: 'ㄷ셋 3',
    parts: [
      { type: 'panel',    pos: [-110, 138, 13],   rot: [-90, 0, 0] },  // 벽 (앞) — 연결대 몸통에 밀착
      { type: 'panel',    pos: [-110, 138, -233], rot: [-90, 0, 0] },  // 벽 (뒤) — 연결대 몸통에 밀착
      { type: 'panel',    pos: [-110, 5, -110],   rot: [0, 0, 0] },    // 바닥판 (바닥에 붙여서 ㄱ자연결대 아래 핀 끝이 판 아래면과 딱 맞는다)
      { type: 'lbracket', pos: [-220, 28, 0],     rot: [0, 90, 90] },
      { type: 'lbracket', pos: [0, 28, 0],        rot: [0, 90, 90] },
      { type: 'lbracket', pos: [-220, 28, -220],  rot: [0, 90, 90] },
      { type: 'lbracket', pos: [0, 28, -220],     rot: [0, 90, 90] }
    ]
  };
  // 의자세트 = ㄷ셋 3(바닥판 + 앞·뒷벽) 위에 ㄴ셋(의자 판 + 등받이 벽)을 올리고, 의자 판과 앞·뒷벽 사이를 ㅁ셋 1처럼 ㄱ자연결대 4개(높이 248)로 이은 것.
  // ㄴ셋은 바닥판이 ㅁ셋 1의 위쪽 판 높이(가운데 271)에 오도록 266만큼 올렸다: 핀 끝이 판 윗면과 딱 맞고, 벽 윗줄 구멍(248)에 핀이 들어간다.
  SETS.chair = {
    label: '의자세트',
    parts: SETS.dset3.parts
      // 등받이(ㄴ셋) 연결대는 다리쪽 연결대와 같은 판 구멍에 위아래로 겹치지 않도록 안쪽으로 한 칸(20)씩 옮긴다: A1→A2, A12→A11
      .concat(SETS.lset.parts.map(sp => ({ type: sp.type, pos: [sp.type === 'lbracket' ? sp.pos[0] + (sp.pos[0] < -110 ? 20 : -20) : sp.pos[0], sp.pos[1] + 266, sp.pos[2]], rot: sp.rot })))
      .concat([-220, 0].flatMap(z => [-220, 0].map(x => ({ type: 'lbracket', pos: [x, 248, z], rot: [0, 0, 90] }))))
  };
  // ㅁ셋 2 = ㅁ셋 1 전체를 Z축으로 +90° 돌린 것 (조립체 가운데 x=-110, y=138 둘레). Z 회전은 마지막에 적용되므로 각 부품의 Z 각도에 90을 더하면 된다.
  SETS.mset2 = {
    label: 'ㅁ셋 2',
    parts: SETS.mset.parts.map(sp => ({
      type: sp.type,
      pos: [-110 - (sp.pos[1] - 138), 138 + (sp.pos[0] + 110), sp.pos[2]],
      rot: [sp.rot[0], sp.rot[1], sp.rot[2] + 90]
    }))
  };
  return SETS;
})();
